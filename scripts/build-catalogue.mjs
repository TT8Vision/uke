/* Build step: data/products/*.json -> data/products.json
 *
 * The per-product files under data/products/ are the source of truth (that is what the
 * Decap folder collection edits). The site, renderer and cart still read one
 * data/products.json, so this stitches them back together.
 *
 * Netlify runs this on every push (see netlify.toml), so a product saved in the CMS is
 * live after the rebuild. Run it locally with: npm run build:catalogue
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';

const SRC = 'data/products';
const OUT = 'data/products.json';

const FIELDS = ['id', 'brand', 'name', 'volume', 'price', 'oldPrice', 'sku',
  'image', 'categories', 'tag', 'inStock', 'new', 'dateAdded'];

const files = (await readdir(SRC)).filter(f => f.endsWith('.json'));

const products = [];
for (const f of files) {
  const p = JSON.parse(await readFile(path.join(SRC, f), 'utf8'));

  // The filename is the id. Trust it over the field, and repair the field if a hand-edit
  // or a CMS quirk ever leaves them disagreeing — the featured lists key off this id.
  const idFromName = path.basename(f, '.json');
  if (p.id !== idFromName) {
    console.warn(`[build] ${f}: id field "${p.id}" != filename — using filename`);
    p.id = idFromName;
  }

  const ordered = {};
  for (const field of FIELDS) ordered[field] = field in p ? p[field] : null;
  products.push(ordered);
}

products.sort((a, b) => a.id.localeCompare(b.id));

// Guard: the site keys everything off id, so a duplicate would silently shadow a product.
const ids = products.map(p => p.id);
const dupes = ids.filter((v, i) => ids.indexOf(v) !== i);
if (dupes.length) {
  console.error(`[build] duplicate ids: ${[...new Set(dupes)].join(', ')}`);
  process.exit(1);
}

// The output is a build artifact. Say so in the file itself, as its first key, so anyone
// who opens it sees the warning before the data. Readers key off `products` and ignore this.
const GENERATED_NOTE =
  'GENERATED by npm run build:catalogue from data/products/*.json — do not edit by hand';

await writeFile(OUT, JSON.stringify({ _comment: GENERATED_NOTE, products }, null, 2) + '\n');

const memberships = products.reduce((n, p) => n + (p.categories?.length ?? 0), 0);
console.log(`products     : ${products.length}`);
console.log(`memberships  : ${memberships}`);
console.log(`wrote        : ${OUT}`);

/* Export: Supabase public.products -> data/products/*.json + data/products.json
 *
 * Supabase is the source of truth for the catalogue. This pulls every row back
 * into the repo so git holds a readable, diffable snapshot of what the shop is
 * selling — a backup and a review surface, never an input. Nothing on the site
 * reads these files at runtime; js/render-products.js queries Supabase directly.
 *
 * The shape is exactly what scripts/build-catalogue.mjs produced when the Decap
 * folder collection was the source of truth, so anything that understood the old
 * catalogue still understands this one.
 *
 * Reads are public under RLS, so this needs no credentials.
 *
 *   npm run export:catalogue
 */
import { readdir, writeFile, unlink } from 'node:fs/promises';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const SUPABASE_URL = 'https://xwgpaalydysfebyolern.supabase.co';
const PUBLISHABLE_KEY = 'sb_publishable_bO3j0H1obZi7Db8AAHUKfA_H-g_EXa9';
const PAGE = 1000;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'data', 'products');
const OUT = join(root, 'data', 'products.json');

// Field order and names as the site has always known them (camelCase), which is
// not the column order Postgres returns (snake_case).
const FIELDS = ['id', 'brand', 'name', 'volume', 'price', 'oldPrice', 'sku',
  'image', 'categories', 'tag', 'inStock', 'new', 'dateAdded'];

function fromRow(r) {
  return {
    id: r.id,
    brand: r.brand,
    name: r.name,
    volume: r.volume,
    price: r.price == null ? null : Number(r.price),
    oldPrice: r.old_price == null ? null : Number(r.old_price),
    sku: r.sku,
    image: r.image,
    categories: r.categories ?? [],
    tag: r.tag,
    inStock: r.in_stock,
    new: r.is_new,
    dateAdded: r.date_added,
  };
}

/* Paged so the export does not depend on PostgREST's default row cap. */
async function fetchAll() {
  const rows = [];
  for (let offset = 0; ; offset += PAGE) {
    const url = `${SUPABASE_URL}/rest/v1/products` +
      `?select=*&order=id.asc&limit=${PAGE}&offset=${offset}`;
    const res = await fetch(url, {
      headers: { apikey: PUBLISHABLE_KEY, Authorization: `Bearer ${PUBLISHABLE_KEY}` },
    });
    if (!res.ok) {
      throw new Error(`products fetch failed: HTTP ${res.status} ${await res.text()}`);
    }
    const page = await res.json();
    rows.push(...page);
    if (page.length < PAGE) return rows;
  }
}

async function main() {
  const rows = await fetchAll();
  if (!rows.length) {
    // An empty table almost certainly means something is wrong, and writing the
    // snapshot anyway would delete every product file in the repo.
    throw new Error('public.products returned no rows');
  }

  const products = rows.map(fromRow);

  // The site keys everything off id, so a duplicate would silently shadow a product.
  const ids = products.map((p) => p.id);
  const dupes = ids.filter((v, i) => ids.indexOf(v) !== i);
  if (dupes.length) throw new Error(`duplicate ids: ${[...new Set(dupes)].join(', ')}`);

  // One file per product, ordered fields, filename == id.
  const written = new Set();
  for (const p of products) {
    const ordered = {};
    for (const field of FIELDS) ordered[field] = field in p ? p[field] : null;
    await writeFile(join(SRC, `${p.id}.json`), JSON.stringify(ordered, null, 2) + '\n');
    written.add(`${p.id}.json`);
  }

  // A product deleted in Supabase must disappear from the snapshot too, or the
  // backup slowly fills with products the shop no longer sells.
  const existing = (await readdir(SRC)).filter((f) => f.endsWith('.json'));
  let removed = 0;
  for (const f of existing) {
    if (written.has(f)) continue;
    await unlink(join(SRC, f));
    console.log(`  removed ${basename(f)} (no longer in Supabase)`);
    removed++;
  }

  const GENERATED_NOTE =
    'GENERATED by npm run export:catalogue from Supabase public.products — do not edit by hand';
  await writeFile(OUT, JSON.stringify({ _comment: GENERATED_NOTE, products }, null, 2) + '\n');

  const memberships = products.reduce((n, p) => n + (p.categories?.length ?? 0), 0);
  console.log(`products     : ${products.length}`);
  console.log(`memberships  : ${memberships}`);
  if (removed) console.log(`removed      : ${removed}`);
  console.log(`wrote        : data/products/*.json and data/products.json`);
}

// Set exitCode rather than calling process.exit(): forcing exit while fetch's
// sockets are still closing trips a libuv assertion on Windows and replaces the
// status with a crash code, which would make failures unscriptable.
try {
  await main();
} catch (err) {
  console.error(`Refusing to export: ${err.message}`);
  process.exitCode = 1;
}
